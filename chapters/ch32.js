/* 字节数组 → 十六进制串 */
function _c32hex(bytes) {
  var out = '';
  for (var i = 0; i < bytes.length; i++) out += (bytes[i] < 16 ? '0' : '') + bytes[i].toString(16);
  return out;
}

/* 十六进制串 → 256 字节的 S 盒；长度不对返回 null */
function _c32sbox(hex) {
  var h = window.CRYPTO.normHex(hex);
  if (h.length !== 512) return null;
  var sbox = new Uint8Array(256);
  for (var i = 0; i < 256; i++) sbox[i] = parseInt(h.substr(i * 2, 2), 16);
  return sbox;
}

/* 参数化的 AES-128 单块加密：把 S 盒当参数传进来，用来做「对拍」
   —— 结构与 assets/labs.js 里的标准实现一致，只是换了 S 盒。
   校验方式：传标准 S 盒时，输出必须等于 FIPS-197 的测试向量
   69c4e0d86a7b0430d8cdb78070b4c55a（key=000102...0f, pt=00112233445566778899aabbccddeeff）。 */
function _c32aesBlock(key, block, sbox) {
  var xt = function (a) { return ((a << 1) ^ ((a & 0x80) ? 0x1b : 0)) & 0xff; };
  var mul = function (a, b) { var r = 0; while (b) { if (b & 1) r ^= a; a = xt(a); b >>= 1; } return r & 0xff; };
  var Nk = key.length / 4, Nr = Nk + 6;
  var w = new Uint8Array(16 * (Nr + 1));
  w.set(key);
  var rcon = 1;
  for (var i = Nk; i < 4 * (Nr + 1); i++) {
    var t = [w[(i - 1) * 4], w[(i - 1) * 4 + 1], w[(i - 1) * 4 + 2], w[(i - 1) * 4 + 3]];
    if (i % Nk === 0) {
      t = [sbox[t[1]], sbox[t[2]], sbox[t[3]], sbox[t[0]]];
      t[0] ^= rcon;
      rcon = xt(rcon);
    }
    for (var k = 0; k < 4; k++) w[i * 4 + k] = w[(i - Nk) * 4 + k] ^ t[k];
  }
  var s = Uint8Array.from(block);
  var addRK = function (r) { for (var j = 0; j < 16; j++) s[j] ^= w[r * 16 + j]; };
  addRK(0);
  for (var round = 1; round <= Nr; round++) {
    for (var q = 0; q < 16; q++) s[q] = sbox[s[q]];
    var cp = Uint8Array.from(s);
    for (var c = 0; c < 4; c++) for (var rr = 0; rr < 4; rr++) s[c * 4 + rr] = cp[((c + rr) % 4) * 4 + rr];
    if (round !== Nr) {
      for (var cc = 0; cc < 4; cc++) {
        var a = [s[cc * 4], s[cc * 4 + 1], s[cc * 4 + 2], s[cc * 4 + 3]];
        s[cc * 4] = mul(a[0], 2) ^ mul(a[1], 3) ^ a[2] ^ a[3];
        s[cc * 4 + 1] = a[0] ^ mul(a[1], 2) ^ mul(a[2], 3) ^ a[3];
        s[cc * 4 + 2] = a[0] ^ a[1] ^ mul(a[2], 2) ^ mul(a[3], 3);
        s[cc * 4 + 3] = mul(a[0], 3) ^ a[1] ^ a[2] ^ mul(a[3], 2);
      }
    }
    addRK(round);
  }
  return s;
}

