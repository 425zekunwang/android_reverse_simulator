function _c32verdictOf(t) {
  if (t.conclusion) return t.verifiability >= 2 ? '协作' : '人';
  if (t.verifyCost <= 1 && t.verifiability >= 3) return 'AI';
  return '协作';
}
/* 解析读者填写的「T1=AI」这类判定行 */
function _c32parseAssign(text) {
  var out = {};
  String(text || '').split('\n').forEach(function (line) {
    var m = /T\s*([1-5])/i.exec(line);
    if (!m) return;
    var id = 'T' + m[1];
    var rest = line.slice(m.index + m[0].length).replace(/^[\s=:：\-—>]+/, '');
    var tok = (rest.split(/[\s,，;；/、（）()]+/)[0] || '').trim();
    var r = '?';
    if (/协作|coop/i.test(tok)) r = '协作';
    else if (/^(人|人工|人主导|human|手动)$/i.test(tok)) r = '人';
    else if (/^(ai|模型|机器|大模型|machine)$/i.test(tok)) r = 'AI';
    if (r !== '?') out[id] = r;
  });
  return out;
}
/* 从读者的「T1=…」行里取出该任务对应的整行文本（用于检查验证手段） */
function _c32lineOf(text, id) {
  var lines = String(text || '').split('\n');
  for (var i = 0; i < lines.length; i++) {
    if (new RegExp('T\\s*' + id.slice(1) + '\\b', 'i').test(lines[i])) return lines[i];
  }
  return '';
}

